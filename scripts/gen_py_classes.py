"""Write the character-class tables of the reference interpreter.

``crates/hygiene/data/py_classes.txt`` holds the code points Python's ``\\w``, ``\\s`` and
``\\d`` match, as inclusive hex ranges, one ``[section]`` per class. The Rust predicates and
regex classes are built from this file alone (never from the ``regex`` crate's Unicode
tables, which are a different version), so it is generated from the pinned interpreter:

    <python 3.13> scripts/gen_py_classes.py          # write the file
    <python 3.13> scripts/gen_py_classes.py --check  # fail if the file is not what this writes

It refuses any interpreter whose Unicode database is not the pinned one, and checks every
code point against the definitions in ``docs/patterns-semantics.md`` (``str.isalnum()`` or
``_``, ``str.isspace()``, category ``Nd``) before writing anything.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path

PINNED_UNICODE = "15.1.0"
TARGET = Path(__file__).resolve().parent.parent / "crates/hygiene/data/py_classes.txt"
LAST = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)
WIDTH = 100
HEADER = (
    "# Python's \\w, \\s and \\d as inclusive code point ranges (hex), Python 3.13, Unicode "
    f"{PINNED_UNICODE}.\n"
    "# Generated by scripts/gen_py_classes.py. Do not edit; regenerate it.\n"
)
# Each class: its pattern in `re`, and its definition by `str` methods and `unicodedata`.
CLASSES: dict[str, tuple[str, Callable[[str], bool]]] = {
    "word": (r"\w", lambda c: c.isalnum() or c == "_"),
    "space": (r"\s", lambda c: c.isspace()),
    "digit": (r"\d", lambda c: unicodedata.category(c) == "Nd"),
}


def ranges(pattern: str, definition: Callable[[str], bool]) -> list[tuple[int, int]]:
    """The inclusive runs `re` matches, each code point checked against ``definition``."""
    find = re.compile(pattern).fullmatch
    runs: list[tuple[int, int]] = []
    for code in range(LAST + 1):
        if code in SURROGATES:
            continue
        char = chr(code)
        member = find(char) is not None
        if member != definition(char):
            raise SystemExit(f"re {pattern!r} and its definition differ at U+{code:04X}")
        if not member:
            continue
        if runs and runs[-1][1] == code - 1:
            runs[-1] = (runs[-1][0], code)
        else:
            runs.append((code, code))
    return runs


def render() -> str:
    """The whole file: the header, then each class's runs, wrapped at `WIDTH` columns."""
    if unicodedata.unidata_version != PINNED_UNICODE:
        raise SystemExit(f"Unicode {unicodedata.unidata_version}, the pin is {PINNED_UNICODE}")
    out = [HEADER]
    for name, (pattern, definition) in CLASSES.items():
        out.append(f"[{name}]\n")
        line = ""
        for low, high in ranges(pattern, definition):
            token = f"{low:x}-{high:x}"
            if line and len(line) + 1 + len(token) > WIDTH:
                out.append(line + "\n")
                line = ""
            line = f"{line} {token}" if line else token
        out.append(line + "\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET} is not what this interpreter writes", file=sys.stderr)
            return 1
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
