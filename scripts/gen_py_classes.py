"""Write the character-class tables of the running interpreter.

``crates/hygiene/data/py_classes_<major>_<minor>.txt`` holds the code points Python's ``\\w``,
``\\s`` and ``\\d`` match, as inclusive hex ranges, one ``[section]`` per class, for one Unicode
version. The Rust predicates and regex classes are built from these files alone (never from the
``regex`` crate's Unicode tables, which are a different version). The three versions the core
ships are the ones CPython 3.12 (15.0.0), 3.13 (15.1.0) and 3.14 (16.0.0, free-threaded 3.14t
too) carry, so each file is written by the interpreter that has it:

    uv run --python 3.12 scripts/gen_py_classes.py          # write its file and its corpus line
    uv run --python 3.12 scripts/gen_py_classes.py --check  # fail unless both are what it writes
    uv run --python 3.12 scripts/gen_py_classes.py --jsonl  # print its ``classes.jsonl`` line

It refuses an interpreter whose Unicode database is not one of the three, and checks every code
point against the definitions in ``docs/patterns-semantics.md`` (``str.isalnum()`` or ``_``,
``str.isspace()``, category ``Nd``) before writing anything. ``corpus/classes.jsonl`` holds one
line per version, ascending, written by ``--jsonl``.
"""

from __future__ import annotations

import json
import re
import sys
import unicodedata
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUPPORTED = ("15.0.0", "15.1.0", "16.0.0")
CORPUS = ROOT / "corpus/classes.jsonl"
LAST = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)
WIDTH = 100
# Each class: its pattern in `re`, and its definition by `str` methods and `unicodedata`.
CLASSES: dict[str, tuple[str, Callable[[str], bool]]] = {
    "word": (r"\w", lambda c: c.isalnum() or c == "_"),
    "space": (r"\s", lambda c: c.isspace()),
    "digit": (r"\d", lambda c: unicodedata.category(c) == "Nd"),
}


def ranges(pattern: str, definition: Callable[[str], bool]) -> list[tuple[int, int]]:
    """The inclusive runs `re` matches, each code point checked against ``definition``."""
    find = re.compile(pattern).fullmatch
    runs: list[tuple[int, int]] = []
    for code in range(LAST + 1):
        if code in SURROGATES:
            continue
        char = chr(code)
        member = find(char) is not None
        if member != definition(char):
            raise SystemExit(f"re {pattern!r} and its definition differ at U+{code:04X}")
        if not member:
            continue
        if runs and runs[-1][1] == code - 1:
            runs[-1] = (runs[-1][0], code)
        else:
            runs.append((code, code))
    return runs


def version() -> str:
    """The running interpreter's Unicode version, refused unless the core ships its tables."""
    if unicodedata.unidata_version not in SUPPORTED:
        raise SystemExit(
            f"Unicode {unicodedata.unidata_version} is not one of {', '.join(SUPPORTED)}"
        )
    return unicodedata.unidata_version


def target(unicode_version: str) -> Path:
    """The table file of a Unicode version: 15.1.0 is ``py_classes_15_1.txt``."""
    major, minor, _ = unicode_version.split(".")
    return ROOT / f"crates/hygiene/data/py_classes_{major}_{minor}.txt"


def compute() -> dict[str, list[tuple[int, int]]]:
    """Each class's runs under the running interpreter, in the order of `CLASSES`."""
    return {name: ranges(pattern, definition) for name, (pattern, definition) in CLASSES.items()}


def render(unicode_version: str, runs: dict[str, list[tuple[int, int]]]) -> str:
    """The whole file: the header, then each class's runs, wrapped at `WIDTH` columns."""
    out = [
        "# Python's \\w, \\s and \\d as inclusive code point ranges (hex), Unicode "
        f"{unicode_version}.\n"
        "# Generated by scripts/gen_py_classes.py. Do not edit; regenerate it.\n"
    ]
    for name, found in runs.items():
        out.append(f"[{name}]\n")
        line = ""
        for low, high in found:
            token = f"{low:x}-{high:x}"
            if line and len(line) + 1 + len(token) > WIDTH:
                out.append(line + "\n")
                line = ""
            line = f"{line} {token}" if line else token
        out.append(line + "\n")
    return "".join(out)


def jsonl(unicode_version: str, runs: dict[str, list[tuple[int, int]]]) -> str:
    """The ``classes.jsonl`` line of this version: ranges per class, keys sorted."""
    return json.dumps({"unicode": unicode_version, **runs}, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    unicode_version = version()
    runs = compute()
    text, line = render(unicode_version, runs), jsonl(unicode_version, runs)
    path = target(unicode_version)
    if argv == ["--jsonl"]:
        sys.stdout.write(line)
        return 0
    if argv == ["--check"]:
        # Bytes, not text: `read_text` would translate a CRLF checkout into the expected file.
        problems: list[str] = []
        if path.read_bytes() != text.encode("utf-8"):
            problems.append(f"{path} is not what this interpreter writes")
        if line.encode("utf-8") not in CORPUS.read_bytes().splitlines(keepends=True):
            problems.append(f"{CORPUS} has no line this interpreter writes")
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    path.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
